const Text& Get(Id id)
{
    static const Text table[] = {
        MakeDeDe(),
        MakeEnUs(),
        MakeEs419(),
        MakeEsEs(),
        MakeFrFr(),
        MakeHeIl(),
        MakeHuHu(),
        MakeItIt(),
        MakeJaJp(),
        MakeKoKr(),
        MakePlPl(),
        MakePtBr(),
        MakeRuRu(),
        MakeSlSi(),
        MakeThTh(),
        MakeTrTr(),
        MakeViVn(),
        MakeZhCn(),
        MakeZhTw(),
    };
    const auto index = static_cast<size_t>(id);
    if (index >= std::size(table))
        return table[static_cast<size_t>(Id::EnUs)];
    return table[index];
}

void SetLanguageProvider(LanguageProvider provider)
{
    g_provider = provider;
}

const Text& Current()
{
    const unsigned short langId = g_provider ? g_provider() : 0;
    return Get(FromLanguageId(langId));
}

